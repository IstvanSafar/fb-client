#!/bin/sh
# Runs inside the container (started by build.ps1). Output: out/fb-client.apk
set -eu

VERSION_CODE=11
VERSION_NAME=3.2
# DEBUG=true (build.ps1 -Debug): the WebView can be inspected over adb
DEBUG=${DEBUG:-false}
MIN_SDK=33
TARGET_SDK=36
# Installed application id. Kept from the first release so updates install over it.
APPLICATION_ID=hu.otthon.fbkliens

BT=/sdk/build-tools
JAR=/sdk/android.jar
cd /src

rm -rf build
mkdir -p build/gen build/classes build/dex out

"$BT/aapt2" compile --dir app/res -o build/res.zip
"$BT/aapt2" link -o build/app-unaligned.apk -I "$JAR" \
  --manifest app/AndroidManifest.xml -A app/assets --java build/gen \
  --rename-manifest-package $APPLICATION_ID \
  --min-sdk-version $MIN_SDK --target-sdk-version $TARGET_SDK \
  --version-code $VERSION_CODE --version-name $VERSION_NAME \
  build/res.zip

mkdir -p build/gen/home/fbclient
cat > build/gen/home/fbclient/BuildConfig.java <<EOF
package home.fbclient;
/** Generated by build.sh */
final class BuildConfig {
    static final boolean DEBUG_WEBVIEW = $DEBUG;
    static final String VERSION_NAME = "$VERSION_NAME";
}
EOF

javac --release 17 -nowarn -cp "$JAR" -d build/classes $(find app/java build/gen -name '*.java')
java -cp "$BT/lib/d8.jar" com.android.tools.r8.D8 --release --min-api $MIN_SDK --lib "$JAR" \
  --output build/dex $(find build/classes -name '*.class')
(cd build/dex && zip -q ../app-unaligned.apk classes.dex)

"$BT/zipalign" -p -f 4 build/app-unaligned.apk build/app-aligned.apk

# Signing key: created on the first build, and the same key is needed from then on,
# otherwise updates will not install over the old version. keystore/ is not in git.
if [ ! -f keystore/release.jks ]; then
  mkdir -p keystore
  head -c 24 /dev/urandom | base64 | tr -d '\n' > keystore/password.txt
  keytool -genkeypair -keystore keystore/release.jks -storetype PKCS12 \
    -storepass:file keystore/password.txt -keypass:file keystore/password.txt \
    -alias fbclient -keyalg RSA -keysize 2048 -validity 10000 \
    -dname "CN=fb-client" > /dev/null 2>&1
  echo "New signing key: keystore/release.jks (back it up!)"
fi

java -jar "$BT/lib/apksigner.jar" sign --ks keystore/release.jks --ks-pass file:keystore/password.txt \
  --ks-key-alias fbclient --out out/fb-client.apk build/app-aligned.apk
rm -f out/fb-client.apk.idsig

ls -l out/fb-client.apk
